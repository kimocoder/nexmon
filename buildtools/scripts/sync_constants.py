#!/usr/bin/env python3
"""Single-source IOCTL and capability constants across Nexmon.

Extracts canonical definitions from:
  - patches/include/nexioctls.h (NEX_* IOCTL numbers, WLC_* IOCTL numbers)
  - patches/include/capabilities.h (NEX_CAP_* capability bitmasks)

and synchronizes or verifies them against:
  - python/pynexmon/nexmon.py
  - app/app/src/main/java/de/tu_darmstadt/seemoo/nexmon/utils/Nexutil.java
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys
from typing import Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[2]
NEXIOCTLS_H = ROOT / "patches/include/nexioctls.h"
CAPABILITIES_H = ROOT / "patches/include/capabilities.h"
PYNEXMON_PY = ROOT / "python/pynexmon/nexmon.py"
NEXUTIL_JAVA = ROOT / "app/app/src/main/java/de/tu_darmstadt/seemoo/nexmon/utils/Nexutil.java"

CAPS_BEGIN_MARKER = "--- BEGIN AUTOGENERATED CONSTANTS: capabilities.h ---"
CAPS_END_MARKER = "--- END AUTOGENERATED CONSTANTS: capabilities.h ---"
NEX_BEGIN_MARKER = "--- BEGIN AUTOGENERATED CONSTANTS: nexioctls.h (Nexmon IOCTLs) ---"
NEX_END_MARKER = "--- END AUTOGENERATED CONSTANTS: nexioctls.h (Nexmon IOCTLs) ---"


def parse_c_defines(path: Path) -> List[Tuple[str, int, str]]:
    """Parse #define constants from a C header, evaluating expressions safely."""
    results: List[Tuple[str, int, str]] = []
    if not path.is_file():
        raise FileNotFoundError(f"Header not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^\s*#define\s+([A-Za-z0-9_]+)\s+(.+?)(?:/\*.*|//.*)?$", line)
            if not m:
                continue
            name, raw_expr = m.group(1), m.group(2).strip()
            # Clean inline comments
            clean_expr = re.sub(r"/\*.*?\*/", "", raw_expr).strip()
            clean_expr = re.sub(r"//.*$", "", clean_expr).strip()
            if not clean_expr:
                continue

            try:
                # Safely evaluate integers, hex, and bitwise shift expressions e.g. (1 << 2)
                val = eval(clean_expr, {"__builtins__": None}, {})  # noqa: S307
            except (ValueError, SyntaxError, TypeError, NameError):
                val = None

            if isinstance(val, int):
                results.append((name, val, clean_expr))
    return results


def get_canonical_definitions() -> Tuple[List[Tuple[str, int, str]], List[Tuple[str, int, str]], Dict[str, int]]:
    """Extract canonical definitions from C headers."""
    cap_defs = [d for d in parse_c_defines(CAPABILITIES_H) if d[0].startswith("NEX_CAP_")]
    all_nexioctls = parse_c_defines(NEXIOCTLS_H)

    # NEX_* IOCTLs in nexioctls.h (lines 39-71, 93)
    nex_ioctls = [d for d in all_nexioctls if d[0].startswith("NEX_")]
    # WLC_* IOCTLs
    wlc_ioctls = {d[0]: d[1] for d in all_nexioctls if d[0].startswith("WLC_")}

    return cap_defs, nex_ioctls, wlc_ioctls


def generate_python_capabilities_block(cap_defs: List[Tuple[str, int, str]]) -> str:
    lines = [
        f"# {CAPS_BEGIN_MARKER}",
        "# Capabilities of the Nexmon Patch (capabilities.h:39-41)",
    ]
    for name, _, raw in cap_defs:
        # Format raw e.g. (1 << 0) as 1 << 0 for idiomatic Python
        py_expr = raw.strip("()")
        lines.append(f"{name} = {py_expr}")
    lines.append(f"# {CAPS_END_MARKER}")
    return "\n".join(lines)


def generate_python_nexioctls_block(nex_defs: List[Tuple[str, int, str]]) -> str:
    lines = [
        f"# {NEX_BEGIN_MARKER}",
        "# Nexmon IOCTL commands (nexioctls.h:39-71, 93)",
    ]
    for name, val, _ in nex_defs:
        lines.append(f"{name} = {val}")
    lines.append(f"# {NEX_END_MARKER}")
    return "\n".join(lines)


def generate_java_capabilities_block(cap_defs: List[Tuple[str, int, str]]) -> str:
    lines = [
        f"    // {CAPS_BEGIN_MARKER}",
        "    // Capabilities of the Nexmon Patch (capabilities.h:39-41)",
    ]
    for name, _, raw in cap_defs:
        java_expr = raw if raw.startswith("(") and raw.endswith(")") else f"({raw})"
        lines.append(f"    public final static int {name} = {java_expr};")
    lines.append(f"    // {CAPS_END_MARKER}")
    return "\n".join(lines)


def generate_java_nexioctls_block(nex_defs: List[Tuple[str, int, str]]) -> str:
    lines = [
        f"    // {NEX_BEGIN_MARKER}",
        "    // IOCTLs used by Nexmon (nexioctls.h:39-71, 93)",
    ]
    for name, val, _ in nex_defs:
        lines.append(f"    public final static int {name} = {val};")
    lines.append(f"    // {NEX_END_MARKER}")
    return "\n".join(lines)


def replace_or_insert_block(text: str, begin_marker: str, end_marker: str, new_block: str) -> str:
    """Replace an existing marked block or return text unchanged if marker not found."""
    pattern = re.compile(
        re.escape(begin_marker) + r".*?" + re.escape(end_marker),
        re.DOTALL,
    )
    if pattern.search(text):
        return pattern.sub(new_block.strip(), text)
    return text


def update_python_nexmon(path: Path = PYNEXMON_PY) -> bool:
    """Update python/pynexmon/nexmon.py with canonical constants."""
    cap_defs, nex_defs, _ = get_canonical_definitions()
    py_caps = generate_python_capabilities_block(cap_defs)
    py_nex = generate_python_nexioctls_block(nex_defs)

    text = path.read_text(encoding="utf-8")
    if CAPS_BEGIN_MARKER in text and NEX_BEGIN_MARKER in text:
        text = replace_or_insert_block(text, f"# {CAPS_BEGIN_MARKER}", f"# {CAPS_END_MARKER}", py_caps)
        text = replace_or_insert_block(text, f"# {NEX_BEGIN_MARKER}", f"# {NEX_END_MARKER}", py_nex)
    else:
        # Replace the legacy hardcoded constants block (lines 8-28)
        legacy_pattern = re.compile(
            r"# Broadcom WLC and Nexmon IOCTL commands\n(?:[A-Z0-9_]+\s*=\s*\d+\n)+",
            re.MULTILINE,
        )
        wlc_block = (
            "# Broadcom WLC IOCTL commands\n"
            "WLC_GET_PROMISC = 9\n"
            "WLC_SET_PROMISC = 10\n"
            "WLC_DISASSOC = 52\n"
            "WLC_GET_REVINFO = 98\n"
            "WLC_GET_MONITOR = 107\n"
            "WLC_SET_MONITOR = 108\n"
            "WLC_GET_SCANSUPPRESS = 115\n"
            "WLC_SET_SCANSUPPRESS = 116\n"
            "WLC_GET_VAR = 262\n"
            "WLC_SET_VAR = 263\n"
        )
        replacement = f"{py_caps}\n\n{py_nex}\n\n{wlc_block}"
        if legacy_pattern.search(text):
            text = legacy_pattern.sub(replacement, text)
        else:
            raise RuntimeError(f"Could not locate constant insertion point in {path}")

    path.write_text(text, encoding="utf-8")
    return True


def update_java_nexutil(path: Path = NEXUTIL_JAVA) -> bool:
    """Update Nexutil.java with canonical constants."""
    cap_defs, nex_defs, _ = get_canonical_definitions()
    java_caps = generate_java_capabilities_block(cap_defs)
    java_nex = generate_java_nexioctls_block(nex_defs)

    text = path.read_text(encoding="utf-8")
    if CAPS_BEGIN_MARKER in text and NEX_BEGIN_MARKER in text:
        text = replace_or_insert_block(text, f"// {CAPS_BEGIN_MARKER}", f"// {CAPS_END_MARKER}", java_caps)
        text = replace_or_insert_block(text, f"// {NEX_BEGIN_MARKER}", f"// {NEX_END_MARKER}", java_nex)
    else:
        # Replace the legacy NEX_* declarations block
        legacy_pattern = re.compile(
            r"(\s*public final static int NEX_GET_CAPABILITIES = 400;.*?"
            r"public final static int NEX_SET_AMPDU_TX = 421;\n)",
            re.DOTALL,
        )
        replacement = f"\n{java_caps}\n\n{java_nex}\n"
        if legacy_pattern.search(text):
            text = legacy_pattern.sub(replacement, text)
        else:
            raise RuntimeError(f"Could not locate constant insertion point in {path}")

    path.write_text(text, encoding="utf-8")
    return True


def check_sync() -> List[str]:
    """Verify that Python and Java constants are in 100% sync with C headers."""
    errors: List[str] = []
    cap_defs, nex_defs, wlc_defs = get_canonical_definitions()

    canonical_caps = {name: val for name, val, _ in cap_defs}
    canonical_nex = {name: val for name, val, _ in nex_defs}

    # 1. Check Python pynexmon/nexmon.py
    py_text = PYNEXMON_PY.read_text(encoding="utf-8")
    py_constants: Dict[str, int] = {}
    for line in py_text.splitlines():
        m = re.match(r"^([A-Z][A-Za-z0-9_]+)\s*=\s*(.+?)(?:#.*)?$", line)
        if m:
            name, raw = m.group(1), m.group(2).strip()
            try:
                py_constants[name] = eval(raw, {"__builtins__": None}, {})  # noqa: S307
            except Exception:
                pass

    # Capabilities in Python
    for name, expected in canonical_caps.items():
        if name not in py_constants:
            errors.append(f"{PYNEXMON_PY}: missing capability constant {name} (expected {expected})")
        elif py_constants[name] != expected:
            errors.append(f"{PYNEXMON_PY}: capability {name}={py_constants[name]} != canonical {expected}")

    # NEX_* IOCTLs in Python
    for name, expected in canonical_nex.items():
        if name not in py_constants:
            errors.append(f"{PYNEXMON_PY}: missing IOCTL constant {name} (expected {expected})")
        elif py_constants[name] != expected:
            errors.append(f"{PYNEXMON_PY}: IOCTL {name}={py_constants[name]} != canonical {expected}")

    # WLC_* IOCTLs present in Python
    for name, val in py_constants.items():
        if name.startswith("WLC_"):
            if name not in wlc_defs:
                errors.append(f"{PYNEXMON_PY}: {name} not found in nexioctls.h")
            elif val != wlc_defs[name]:
                errors.append(f"{PYNEXMON_PY}: {name}={val} != canonical {wlc_defs[name]}")

    # 2. Check Java Nexutil.java
    java_text = NEXUTIL_JAVA.read_text(encoding="utf-8")
    java_constants: Dict[str, int] = {}
    for line in java_text.splitlines():
        m = re.match(r"^\s*public\s+final\s+static\s+int\s+([A-Za-z0-9_]+)\s*=\s*(.+?);", line)
        if m:
            name, raw = m.group(1), m.group(2).strip()
            try:
                java_constants[name] = eval(raw, {"__builtins__": None}, {})  # noqa: S307
            except Exception:
                pass

    # Capabilities in Java
    for name, expected in canonical_caps.items():
        if name not in java_constants:
            errors.append(f"{NEXUTIL_JAVA}: missing capability constant {name} (expected {expected})")
        elif java_constants[name] != expected:
            errors.append(f"{NEXUTIL_JAVA}: capability {name}={java_constants[name]} != canonical {expected}")

    # NEX_* IOCTLs in Java
    for name, expected in canonical_nex.items():
        if name not in java_constants:
            errors.append(f"{NEXUTIL_JAVA}: missing IOCTL constant {name} (expected {expected})")
        elif java_constants[name] != expected:
            errors.append(f"{NEXUTIL_JAVA}: IOCTL {name}={java_constants[name]} != canonical {expected}")

    # WLC_* IOCTLs present in Java
    for name, val in java_constants.items():
        if name.startswith("WLC_"):
            if name not in wlc_defs:
                errors.append(f"{NEXUTIL_JAVA}: {name} not found in nexioctls.h")
            elif val != wlc_defs[name]:
                errors.append(f"{NEXUTIL_JAVA}: {name}={val} != canonical {wlc_defs[name]}")

    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--update",
        action="store_true",
        help="Update python/pynexmon/nexmon.py and Nexutil.java with canonical constants from C headers",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check that constants in Python and Java match C headers (default action)",
    )
    args = parser.parse_args()

    if args.update:
        print("Synchronizing IOCTL and capability constants from C headers...")
        update_python_nexmon()
        update_java_nexutil()
        print("Files successfully updated.")

    errors = check_sync()
    if errors:
        print(f"FAILED: Found {len(errors)} constant synchronization error(s):", file=sys.stderr)
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        return 1

    print("SUCCESS: All IOCTL & capability constants are single-sourced and synchronized.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
